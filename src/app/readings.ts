const SORTED = [...READINGS].sort((a, b) => b[0].length - a[0].length);

// 読み上げ用の文に直す
export function toReading(text: string): string {
  let out = text;
  for (const [written, reading] of SORTED) out = out.split(written).join(reading);
  return out;
}

